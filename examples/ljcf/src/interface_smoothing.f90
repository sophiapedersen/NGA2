  ! Function to interpolate vertices intercepting edges
  function InterpManson(p1, p2, valp1, valp2)
    implicit none
    real(SP), intent(in) :: valp1, valp2
    real(SP), dimension(3), intent(in) :: p1, p2
    real(SP), dimension(3) :: InterpManson,buff 
    real(SP) :: mu, a1, a2, a1b, a2b
    integer :: inv,cas 

    if (valp2 > valp1) then
      a1 = valp1
      a2 = valp2
      a1b = 1.0_SP - a2
      a2b = 1.0_SP - a1
      inv = 0
    else
      a1 = valp2
      a2 = valp1
      a1b = 1.0_SP - a2
      a2b = 1.0_SP - a1
      inv = 1
    end if

    if (a2 <= 3.0_SP * a1) then
      if (3.0_SP * a2 <= a1 + 2.0_SP) then
        mu = (a1 - 0.5_SP) / (a1 - a2)
        cas = 1
      else
        if ((2.0_SP * a1b + 2.0_SP * a2b - 1.0_SP)**2 < 4.0_SP * a1b * (a1b + a2b)) then
          mu = (2.0_SP * a2b - 1.0_SP) / (8.0_SP * a1b + 4.0_SP * a2b - 8.0_SP * sqrt(a1b * (a1b + a2b)))
          cas = 4 
        else
          mu = 1.5_SP - a1 - a2
          cas = 2 
        end if
      end if
    else
      if (3.0_SP * a2 > a1 + 2.0_SP) then
        mu = 1.5_SP - a1 - a2
        cas = 2 
      else
        if ((2.0_SP * a1 + 2.0_SP * a2 - 1.0_SP)**2 < 4.0_SP * a1 * (a1 + a2)) then
          mu = 1.0_SP - ((2.0_SP * a2 - 1.0_SP) / (8.0_SP * a1 + 4.0_SP * a2 - 8.0_SP * sqrt(a1 * (a1 + a2))))
          cas = 3 
        else
          mu = 1.5_SP - a1 - a2
          cas = 2 
        end if
      end if
    end if

    if (mu > 1.0_SP - tiny(1.0_SP)) then
      mu = 1.0_SP - tiny(1.0_SP)
    else if (mu < tiny(1.0_SP)) then
      mu = tiny(1.0_SP)
    end if

    if (inv == 1) then
      mu = 1.0_SP - mu
    end if

    buff(1) =  p1(1) + mu * (p2(1) - p1(1))
    buff(2) =  p1(2) + mu * (p2(2) - p1(2)) 
    buff(3) =  p1(3) + mu * (p2(3) - p1(3)) 

    InterpManson = buff 

  end function InterpManson

  function VertexInterp(isolevel, p1, p2, valp1, valp2)
    real(SP), intent(in) :: isolevel, valp1, valp2
    real(SP), dimension(3), intent(in) :: p1, p2
    real(SP), dimension(3) :: buff, VertexInterp
    real :: mu

    if (abs(isolevel-valp1) < 0.00001) then
      VertexInterp = p1
    else if (abs(isolevel-valp2) < 0.00001) then
      VertexInterp = p2
