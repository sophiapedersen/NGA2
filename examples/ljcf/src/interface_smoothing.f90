  subroutine add_triangle(myi, myj, myk, vl, tr, n)
      ! use dump_visit
      implicit none
      integer, intent(in) :: myi, myj, myk, n
      real(SP), dimension(3,12), intent(in) :: vl
      integer, dimension(:), intent(in) :: tr
      integer :: i, zid, tv,nz_old

      nz_old = nZones 

      do i = 1,3*n 
        ! Check if we need a new zone (triangle)
        zid = mod(i-1,3)+1
            
        if (tr(i).ge.1 .and. tr(i).le.12) then 
          !print*, "Print off nNodes"  
          !print*, nNodes   
          nNodes = nNodes+1 
          xNode(nNodes) = real(vl(1,tr(i)),SP)
          yNode(nNodes) = real(vl(2,tr(i)),SP)
          zNode(nNodes) = real(vl(3,tr(i)),SP)
        else 
          call add_c_vertex(vl)
        end if 

        ! Add a new zone every three vertices
        if (zid.eq.3) then   
          ! Check if the tri has 0 area
          if ((xNode(nNodes-2) .eq. xNode(nNodes-1) .and. xNode(nNodes-1) .eq. xNode(nNodes)) .and. &
              (yNode(nNodes-2) .eq. yNode(nNodes-1) .and. yNode(nNodes-1) .eq. yNode(nNodes)) .and. &
              (zNode(nNodes-2) .eq. zNode(nNodes-1) .and. zNode(nNodes-1) .eq. zNode(nNodes))) then
                ! Skip adding this zero-area triangle
                nNodes = nNodes - 3
          else 
            nodeList(3*nZones+1:3*nZones+3) = (/nNodes-2,nNodes-1,nNodes/)
            nZones = nZones + 1
            zoneIndex(:,nZones) = (/myi,myj,myk/)
          end if 
        end if

      end do  

  end subroutine add_triangle 

  subroutine add_c_vertex(vertlist)
    !use interface_smoothing
    !use dump_visit
    implicit none
    real(SP), intent(in), dimension(3,12) :: vertlist
    real(SP) :: xN,yN,zN
    integer :: count  

    ! Initialize count and nodes to 0
    count = 0
    xN = 0.0_SP
    yN = 0.0_SP
    zN = 0.0_SP

    ! Find the vertices where the surface intersects the cube
    if (iand(edgeTable(cubeindex), 1) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,1)
      yN = yN + vertlist(2,1)
      zN = zN + vertlist(3,1) 
    end if
    if (iand(edgeTable(cubeindex), 2) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,2)
      yN = yN + vertlist(2,2)
      zN = zN + vertlist(3,2)
    end if
    if (iand(edgeTable(cubeindex), 4) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,3)
      yN = yN + vertlist(2,3)
      zN = zN + vertlist(3,3)
    end if
    if (iand(edgeTable(cubeindex), 8) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,4)
      yN = yN + vertlist(2,4)
      zN = zN + vertlist(3,4)
    end if
    if (iand(edgeTable(cubeindex), 16) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,5)
      yN = yN + vertlist(2,5)
      zN = zN + vertlist(3,5)
    end if
    if (iand(edgeTable(cubeindex), 32) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,6)
      yN = yN + vertlist(2,6)
      zN = zN + vertlist(3,6)
    end if
    if (iand(edgeTable(cubeindex), 64) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,7)
      yN = yN + vertlist(2,7)
      zN = zN + vertlist(3,7)
    end if
    if (iand(edgeTable(cubeindex), 128) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,8)
      yN = yN + vertlist(2,8)
      zN = zN + vertlist(3,8)
    end if
    if (iand(edgeTable(cubeindex), 256) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,9)
      yN = yN + vertlist(2,9)
      zN = zN + vertlist(3,9)
    end if
    if (iand(edgeTable(cubeindex), 512) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,10)
      yN = yN + vertlist(2,10)
      zN = zN + vertlist(3,10)
    end if
    if (iand(edgeTable(cubeindex), 1024) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,11)
      yN = yN + vertlist(2,11)
      zN = zN + vertlist(3,11)
    end if
    if (iand(edgeTable(cubeindex), 2048) /= 0) then
      count = count + 1
      xN = xN + vertlist(1,12)
      yN = yN + vertlist(2,12)
      zN = zN + vertlist(3,12)
    end if
    
    ! Average the points to a point in the center
    nNodes = nNodes+1
    xNode(nNodes) = real(xN / count,SP) 
    yNode(nNodes) = real(yN / count,SP) 
    zNode(nNodes) = real(zN / count,SP)
    nodeList(3*nZones+1) = nNodes

  end subroutine add_c_vertex
