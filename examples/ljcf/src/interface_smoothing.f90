          t = cb(3) / (cb(3) - cb(7))
          Bt = cb(2) + (cb(6) - cb(2)) * t
          Ct = cb(1) + (cb(5) - cb(1)) * t
          Dt = cb(4) + (cb(8) - cb(4)) * t
        case (11)
          t = cb(4) / (cb(4) - cb(8))
          Bt = cb(3) + (cb(7) - cb(3)) * t
          Ct = cb(2) + (cb(6) - cb(2)) * t
          Dt = cb(1) + (cb(5) - cb(1)) * t
        case default
          print *, "Invalid edge ", edge
          stop
      end select
    else
      print *, "Invalid ambiguous case ", cs
      stop
    end if

    if (At >= 0.0_SP) test = test + 1
    if (Bt >= 0.0_SP) test = test + 2
    if (Ct >= 0.0_SP) test = test + 4
    if (Dt >= 0.0_SP) test = test + 8

    if (test == 6 .or. test == 8 .or. test == 9 .or. test == 12 .or. (test >= 0 .and. test <= 4)) then
        test_interior = (s > 0)
    elseif (test == 5) then
        test_interior = (At * Ct - Bt * Dt < tiny(At))
    elseif (test == 10) then
        test_interior = (At * Ct - Bt * Dt >= tiny(At))
    else
        test_interior = (s < 0)
    end if
  end function test_interior

