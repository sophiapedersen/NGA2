        case (0)
          t = cb(1) / (cb(1) - cb(2))
          Bt = cb(4) + (cb(3) - cb(4)) * t
          Ct = cb(8) + (cb(7) - cb(8)) * t
          Dt = cb(5) + (cb(6) - cb(5)) * t
        case (1)
          t = cb(2) / (cb(2) - cb(3))
          Bt = cb(1) + (cb(4) - cb(1)) * t
          Ct = cb(5) + (cb(8) - cb(5)) * t
          Dt = cb(6) + (cb(7) - cb(6)) * t
        case (2)
          t = cb(3) / (cb(3) - cb(4))
          Bt = cb(2) + (cb(1) - cb(2)) * t
          Ct = cb(6) + (cb(5) - cb(6)) * t
          Dt = cb(7) + (cb(8) - cb(7)) * t
        case (3)
          t = cb(4) / (cb(4) - cb(1))
          Bt = cb(3) + (cb(2) - cb(3)) * t
          Ct = cb(7) + (cb(6) - cb(7)) * t
          Dt = cb(8) + (cb(5) - cb(8)) * t
        case (4)
          t = cb(5) / (cb(5) - cb(6))
          Bt = cb(8) + (cb(7) - cb(8)) * t
          Ct = cb(4) + (cb(3) - cb(4)) * t
          Dt = cb(1) + (cb(2) - cb(1)) * t
        case (5)
          t = cb(6) / (cb(6) - cb(7))
          Bt = cb(5) + (cb(8) - cb(5)) * t
          Ct = cb(1) + (cb(4) - cb(1)) * t
          Dt = cb(2) + (cb(3) - cb(2)) * t
        case (6)
          t = cb(7) / (cb(7) - cb(8))
          Bt = cb(6) + (cb(5) - cb(6)) * t
          Ct = cb(2) + (cb(1) - cb(2)) * t
          Dt = cb(3) + (cb(4) - cb(3)) * t
        case (7)
          t = cb(8) / (cb(8) - cb(5))
          Bt = cb(7) + (cb(6) - cb(7)) * t
          Ct = cb(3) + (cb(2) - cb(3)) * t
          Dt = cb(4) + (cb(1) - cb(4)) * t
        case (8)
          t = cb(1) / (cb(1) - cb(5))
          Bt = cb(4) + (cb(8) - cb(4)) * t
          Ct = cb(3) + (cb(7) - cb(3)) * t
          Dt = cb(2) + (cb(6) - cb(2)) * t
        case (9)
          t = cb(2) / (cb(2) - cb(6))
          Bt = cb(1) + (cb(5) - cb(1)) * t
          Ct = cb(4) + (cb(8) - cb(4)) * t
          Dt = cb(3) + (cb(7) - cb(3)) * t
