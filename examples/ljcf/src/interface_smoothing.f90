    else
      mu = (isolevel - valp1) / (valp2 - valp1)

      buff(1) =  p1(1) + mu * (p2(1) - p1(1))
      buff(2) =  p1(2) + mu * (p2(2) - p1(2)) 
      buff(3) =  p1(3) + mu * (p2(3) - p1(3)) 

    VertexInterp = buff 
    end if
  end function VertexInterp

