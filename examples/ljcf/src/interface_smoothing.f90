  logical function test_face(cb, face)
    implicit none
    real(SP), dimension(8), intent(in) :: cb
    integer, intent(in) :: face
    real(SP) :: A, B, C, D
    integer :: af

    af = abs(face)
    select case (af)
        case (1)
            A = cb(1)
            B = cb(5)
            C = cb(6)
            D = cb(2)
        case (2)
            A = cb(2)
            B = cb(6)
            C = cb(7)
            D = cb(3)
        case (3)
            A = cb(3)
            B = cb(7)
            C = cb(8)
            D = cb(4)
        case (4)
            A = cb(4)
            B = cb(8)
            C = cb(5)
            D = cb(1)
        case (5)
            A = cb(1)
            B = cb(4)
            C = cb(3)
            D = cb(2)
        case (6)
            A = cb(5)
            B = cb(8)
            C = cb(7)
            D = cb(6)
        case default
            print *, "Invalid face code ", face
            stop
    end select

    if (abs(A * C - B * D) < tiny(1.0_SP)) then
        test_face = (face >= 0)
    else
        test_face = (face * A * (A * C - B * D) >= 0)
    end if
  end function test_face

  logical function test_interior(cs, cb, cfg, subcfg, s)
    implicit none
    integer, intent(in) :: cs, cfg, subcfg, s
