    At = 0.0_SP
    Bt = 0.0_SP
    Ct = 0.0_SP
    Dt = 0.0_SP

    if (cs == 5 .or. cs == 11) then
      a = (cb(5) - cb(1)) * (cb(7) - cb(3)) - (cb(8) - cb(4)) * (cb(6) - cb(2))
      b = cb(3) * (cb(5) - cb(1)) + cb(1) * (cb(7) - cb(3)) - cb(2) * (cb(8) - cb(4)) - cb(4) * (cb(6) - cb(2))
      t = -b / (2.0_SP * a)
      if (t < 0.0_SP .or. t > 1.0_SP) then
        test_interior = (s > 0)
        return
      end if

      At = cb(1) + (cb(5) - cb(1)) * t
      Bt = cb(4) + (cb(8) - cb(4)) * t
      Ct = cb(3) + (cb(7) - cb(3)) * t
      Dt = cb(2) + (cb(6) - cb(2)) * t
    elseif (cs == 7 .or. cs == 8 .or. cs == 13 .or. cs == 14) then
